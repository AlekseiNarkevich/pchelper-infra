-- ---------------------------------------------------------------------
-- Синхронизация последовательностей SERIAL с фактическими идентификаторами.
-- Без этого первая же вставка без явного id (например, из API) упадёт
-- с нарушением уникальности первичного ключа.
-- ---------------------------------------------------------------------
DO $$
DECLARE tbl text;
BEGIN
    FOREACH tbl IN ARRAY ARRAY['Процессоры','МатеринскиеПлаты','ОЗУ',
                               'СистемыОхлаждения','Видеокарты','Накопители',
                               'БлокиПитания','Корпуса','ГотовыеКонфигурации',
                               'КонфигурацияНакопители','Пользователи',
                               'ОбновительныеТокены','Сборки','Сборка_Компоненты',
                               'Корзины','Корзина_Позиции','Заказы',
                               'Заказ_Позиции','Промокоды','Отзывы',
                               'ЖурналДействийАгента']
    LOOP
        EXECUTE format(
            'SELECT setval(pg_get_serial_sequence(%L, ''id''),
                           COALESCE((SELECT MAX(id) FROM %I), 1), true)',
            tbl, tbl);
    END LOOP;
END $$;

