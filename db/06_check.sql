--          -f /docker-entrypoint-initdb.d/06_check.sql
--
--  Скрипт НЕ меняет схему и предназначен для демонстрации на защите:
--  он показывает, что модель данных работает именно так, как задумано.
--  Каждая проверка помечена ожидаемым результатом.
-- =====================================================================

\echo '========================================================='
\echo ' ПРОВЕРКА 1. Единый каталог: 8 типов компонентов'
\echo ' Ожидание: 8 строк — по одной на каждый тип'
\echo '========================================================='
SELECT тип, count(*) AS количество
  FROM v_каталог
 GROUP BY тип
 ORDER BY тип;

\echo ''
\echo '========================================================='
\echo ' ПРОВЕРКА 2. Цена готовой конфигурации ВЫЧИСЛЯЕТСЯ'
\echo ' Ожидание: цена = сумма цен компонентов состава'
\echo '========================================================='
SELECT id, название, цена
  FROM v_готовые_конфигурации
 ORDER BY id;

\echo ''
\echo '========================================================='
\echo ' ПРОВЕРКА 3. Правило 7 — запас мощности БП 25 %'
\echo ' ceil((TDP CPU 120 + TDP GPU 245) * 1.25) = 457 Вт'
\echo ' Ожидание: БП 650 Вт подходит, ошибки нет'
\echo '========================================================='
SELECT уровень, код, сообщение
  FROM fn_check_compatibility(2, 1, 1, 1, 1, ARRAY[1], 1, 1);

\echo ''
\echo '========================================================='
\echo ' ПРОВЕРКА 4. Несовместимая сборка'
\echo ' CPU AM5 + плата LGA1700 + память DDR4 + корпус Micro-ATX'
\echo ' Ожидание: минимум три ошибки'
\echo '========================================================='
SELECT уровень, код, сообщение
  FROM fn_check_compatibility(1, 3, 2, 2, NULL, ARRAY[2, 1], 2, 1);

\echo ''
\echo '========================================================='
\echo ' ПРОВЕРКА 5. Складские остатки, которые заканчиваются'
\echo '========================================================='
SELECT тип_компонента, идентификатор, название,
       количество, зарезервировано, доступно, заканчивается
  FROM v_остатки
 WHERE заканчивается
 ORDER BY тип_компонента;

\echo ''
\echo '========================================================='
\echo ' ПРОВЕРКА 6. Справочник разрешённых переходов статуса'
\echo '========================================================='
SELECT из_status, в_status, роль_кто
  FROM "ПереходыСтатусовЗаказа"
 ORDER BY из_status, в_status;

\echo ''
\echo '========================================================='
\echo ' ПРОВЕРКА 7. ЗАПРЕТ отмены доставленного заказа (триггер БД)'
\echo ' Ожидание: ОШИБКА «нельзя отменить»'
\echo '========================================================='
UPDATE "Заказы" SET статус = 'Отменён' WHERE номер = 'PCH-2026-000004';

\echo ''
\echo '========================================================='
\echo ' ПРОВЕРКА 8. ЗАПРЕТ отмены отправленного заказа'
\echo ' Ожидание: ОШИБКА «нельзя отменить»'
\echo '========================================================='
UPDATE "Заказы" SET статус = 'Отменён' WHERE номер = 'PCH-2026-000003';

\echo ''
\echo '========================================================='
\echo ' ПРОВЕРКА 9. Отмена заказа «Новый» РАЗРЕШЕНА'
\echo ' Ожидание: UPDATE 1, статус стал «Отменён»'
\echo '========================================================='
UPDATE "Заказы" SET статус = 'Отменён' WHERE номер = 'PCH-2026-000001';
SELECT номер, статус FROM "Заказы" WHERE номер = 'PCH-2026-000001';

\echo ''
\echo '========================================================='
\echo ' ПРОВЕРКА 10. CHECK «ровно одна ссылка на компонент»'
\echo ' Вставка двух ссылок в одной позиции корзины'
\echo ' Ожидание: ОШИБКА о нарушении chk_single_cart_component'
\echo '========================================================='
INSERT INTO "Корзина_Позиции" (корзина_id, количество, цена, процессор_id, озу_id)
VALUES (1, 1, 599, 1, 1);

\echo ''
\echo '========================================================='
\echo ' ПРОВЕРКА 11. Недопустимый переход статуса менеджером'
\echo ' «В обработке» -> «Доставлен» разрешённым переходом не является'
\echo '========================================================='
SELECT р.из_status, р.в_status
  FROM "ПереходыСтатусовЗаказа" р
 WHERE р.из_status = 'В обработке';

\echo ''
\echo '========================================================='
\echo ' ПРОВЕРКА 12. Снимок цены в позиции заказа'
\echo ' Даже если изменить цену в каталоге, сумма заказа не изменится'
\echo '========================================================='
SELECT оп.название, оп.цена_за_единицу, оп.количество, оп.сумма
  FROM "Заказ_Позиции" оп
 WHERE оп.заказ_id = 3
 ORDER BY оп.id;

\echo ''
\echo '========================================================='
\echo ' ПРОВЕРКА 13. Журнал действий агента (маскирование PII)'
\echo '========================================================='
SELECT момент, инструмент, аргументы, результат, код_ответа, успешно
  FROM "ЖурналДействийАгента"
 ORDER BY id DESC
 LIMIT 5;

\echo ''
\echo '========================================================='
\echo ' ПРОВЕРКА 14. Количество индексов и ограничений'
\echo '========================================================='
SELECT
    (SELECT count(*) FROM pg_indexes WHERE schemaname = 'public') AS индексов,
    (SELECT count(*) FROM pg_type    WHERE typname IN ('component_type','user_role',
                                                        'order_status','delivery_method',
                                                        'payment_method','discount_type',
                                                        'review_status')) AS перечислений,
    (SELECT count(*) FROM pg_trigger WHERE NOT tgisinternal) AS триггеров;

\echo ''
\echo ' Проверка завершена.'