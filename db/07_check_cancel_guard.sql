-- =====================================================================
--  PCHelper — проверка запрета отмены доставленного заказа
--  Лабораторная работа № 4, задание 2, пункт 6.
--
--  Вызывается отдельно от db/06_check.sql, чтобы скриншот показывал
--  ровно одну ошибку триггера, а не весь вывод четырнадцати проверок.
--
--  Запуск:
--      docker compose exec -T postgres psql -U pchelper -d pchelper \
--          -f /docker-entrypoint-initdb.d/07_check_cancel_guard.sql
--
--  Ожидаемый результат — ошибка:
--      ERROR:  Недопустимый переход: заказ №PCH-2026-000004
--              в статусе "Доставлен" нельзя отменить
--      CONTEXT:  PL/pgSQL function fn_order_cancel_guard() line 4 at RAISE
-- =====================================================================

\echo '========================================================='
\echo ' ПОПЫТКА ОТМЕНИТЬ ДОСТАВЛЕННЫЙ ЗАКАЗ'
\echo ' Заказ PCH-2026-000004 в статусе «Доставлен»'
\echo ' Ожидание: ОШИБКА от триггера fn_order_cancel_guard()'
\echo '========================================================='

UPDATE "Заказы"
   SET статус = 'Отменён'
 WHERE номер = 'PCH-2026-000004';

\echo ''
\echo '========================================================='
\echo ' КОНТРОЛЬ: статус заказа не изменился'
\echo '========================================================='

SELECT номер, статус FROM "Заказы" WHERE номер = 'PCH-2026-000004';
