-- =====================================================================
--  PCHelper — возврат демонстрационных данных в исходное состояние
--  Лабораторная работа № 4.
--
--  Нужен потому, что проверка 9 в db/06_check.sql действительно
--  отменяет заказ PCH-2026-000001. Если скриншоты снимаются на живой
--  базе, после прогона состояние надо вернуть, иначе повторный
--  прогон покажет UPDATE 0 вместо UPDATE 1 и картинка будет неверной.
--
--  Запуск:
--      docker compose exec -T postgres psql -U pchelper -d pchelper \
--          -f /docker-entrypoint-initdb.d/08_restore_demo_state.sql
-- =====================================================================

\set order_no 'PCH-2026-000001'
\set base_status 'Новый'

\echo '========================================================='
\echo ' ВОЗВРАТ ДЕМО-ДАННЫХ В ИСХОДНОЕ СОСТОЯНИЕ'
\echo '========================================================='

UPDATE "Заказы"
   SET статус = :'base_status'
 WHERE номер = :'order_no';

SELECT номер, статус FROM "Заказы" ORDER BY номер ASC;
